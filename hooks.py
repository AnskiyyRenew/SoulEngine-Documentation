"""
Navigation fix for the i18n `folder` structure.

`mkdocs-static-i18n` strips the top-level language wrapper section (e.g. "En")
from the auto-detected navigation. It does this by matching the section title
against `locale.capitalize()`, which only works for simple locales like `en`
("en" -> "En"). For locales containing an underscore, e.g. `zh_CN`, the section
title is generated by MkDocs as "zh CN" (underscore becomes a space), so the
match fails and a redundant top-level "zh CN" wrapper leaks into the sidebar.

This hook promotes the children of any top-level section whose title matches one
of the configured i18n language folders, giving every language the same clean
top-level navigation. The language list is read from the `i18n` plugin config,
so adding a language in `mkdocs.yml` is enough — no need to edit this file.
"""

from mkdocs.plugins import get_plugin_logger

log = get_plugin_logger("soulengine_lang_nav")


def _normalize(title):
    """Lowercase and strip all non-alphanumeric chars for fuzzy title matching."""
    return "".join(ch for ch in (title or "").lower() if ch.isalnum())


def _language_folders(config):
    try:
        i18n = config.plugins["i18n"]
        return [lang.locale for lang in i18n.config.languages if lang.build]
    except Exception:
        log.warning(
            "Could not read languages from the 'i18n' plugin config; "
            "falling back to default language folders."
        )
        return ["en", "zh_CN"]


def on_nav(nav, config, files):
    language_norms = {_normalize(lang) for lang in _language_folders(config)}

    promoted = []
    for item in nav.items:
        if getattr(item, "is_section", False) and _normalize(item.title) in language_norms:
            promoted.extend(item.children)
        else:
            promoted.append(item)

    if promoted != list(nav.items):
        nav.items = promoted
        log.debug(f"Promoted language wrapper section children ({len(promoted)} items)")

    return nav
